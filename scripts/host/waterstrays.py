#!/usr/bin/env python3
"""BOARDWALK-03 (OWNER 11-08): WHICH BLOCKS STANDING IN WATER DID THE BOTS PLACE? -- the evidence file the bots act on.

READ-ONLY. Nothing here edits a world, a server or a bot. It reads region files and telemetry and writes one JSON file per pool
(`bots/data/waterstrays/<pool>.json`): the bot code (bots/src/boardwalk.mjs) only ever digs a cell this file names, and only while
the world still shows the block the file names there.

THE PROOF IS GENESIS. A fleet world is generated by Paper 1.21.8 build 60 (jar sha256 8de7c52c...) from its seed; nobody but the
bots plays in it (the owner's one-off admin repairs are logged, and TOWN-PLACED.json lists the founder's setup blocks). So a cell
is BOT-PLACED when the SAME jar, given the SAME seed, generates WATER (or open air) there and the live world now holds a bot
material (dirt, grass on placed dirt, cobblestone, the pathfinder's stone-family scaffold). The genesis copy is generated in a
throwaway server directory (never a fleet world, never a sandbox): docs/reports/boardwalk-03-2026-11-08.md has the run.
A second, independent source is the bots' own `_place_town` rows (placeaudit-fleet-01, live since 11-08 09:14Z): a candidate a
bot's row names as placed carries a trailing 1.

  scan    (worlds host)  waterstrays.py scan --live <world> --genesis <world> --home x,y,z [--r 104] [--admin TOWN-PLACED.json] > scan.json
  finish  (bots host)    waterstrays.py finish --scan scan.json --pool P [--pooldir /var/lib/mcai/_pool-P]
                           [--logs '/var/log/mcai/P-*/skill-*.jsonl*'] [--days 7] > bots/data/waterstrays/P.json

A cell counts only in a column that was OPEN WATER at genesis (its genesis surface is water), at or above that water surface
(wy .. wy+3): "standing in water". Submerged bot blocks (below the surface) are counted in the controls, never listed: digging
under water is a swim the bots need not make.

POSITIVE CONTROLS (every scan prints them): the genesis/live agreement of the column tops in the far ring (r-8..r from home,
where bots build least) -- a wrong seed or a different jar reads near 0 there; the genesis water columns; the live columns with a
bot material on top (the denominator); and the columns the surface heuristic (woodworks-1108: a bot material top with water on two
opposite sides) counts that genesis says are NATURAL (the false positives this proof removes).
"""
import argparse, collections, glob, gzip, json, math, os, re, struct, sys, time, zlib


# ---- region reader (anvil, 1.18+ sections) ----------------------------------------------------------------------------------
def _nbt(b, i, t):
    if t == 1: return struct.unpack_from('>b', b, i)[0], i + 1
    if t == 2: return struct.unpack_from('>h', b, i)[0], i + 2
    if t == 3: return struct.unpack_from('>i', b, i)[0], i + 4
    if t == 4: return struct.unpack_from('>q', b, i)[0], i + 8
    if t == 5: return None, i + 4
    if t == 6: return None, i + 8
    if t == 7: n = struct.unpack_from('>i', b, i)[0]; return None, i + 4 + n
    if t == 8: n = struct.unpack_from('>H', b, i)[0]; return b[i + 2:i + 2 + n].decode('utf8', 'replace'), i + 2 + n
    if t == 9:
        et = b[i]; n = struct.unpack_from('>i', b, i + 1)[0]; i += 5; out = []
        for _ in range(n): v, i = _nbt(b, i, et); out.append(v)
        return out, i
    if t == 10:
        d = {}
        while True:
            tt = b[i]; i += 1
            if tt == 0: return d, i
            n = struct.unpack_from('>H', b, i)[0]; name = b[i + 2:i + 2 + n].decode('utf8', 'replace'); i += 2 + n
            v, i = _nbt(b, i, tt); d[name] = v
    if t == 11: n = struct.unpack_from('>i', b, i)[0]; return None, i + 4 + 4 * n
    if t == 12: n = struct.unpack_from('>i', b, i)[0]; return list(struct.unpack_from('>%dq' % n, b, i + 4)), i + 4 + 8 * n
    raise ValueError(t)


class World:
    """block(x, y, z) -> name (+ '[wl]' when waterlogged) | '?' (chunk not generated in full, or unreadable)."""
    def __init__(self, path):
        self.path, self.regs, self.chunks = path, {}, {}

    def _chunk(self, cx, cz):
        k = (cx, cz)
        if k in self.chunks: return self.chunks[k]
        f = f'{self.path}/region/r.{cx >> 5}.{cz >> 5}.mca'
        if f not in self.regs: self.regs[f] = open(f, 'rb').read() if os.path.exists(f) else b''
        d = self.regs[f]; secs = None
        i = 4 * ((cx & 31) + (cz & 31) * 32)
        off = int.from_bytes(d[i:i + 3], 'big') if len(d) > i + 3 else 0
        if off:
            try:
                o = off * 4096; ln = struct.unpack_from('>i', d, o)[0]
                raw = zlib.decompress(d[o + 5:o + 4 + ln])
                root, _ = _nbt(raw, 3 + struct.unpack_from('>H', raw, 1)[0], 10)
                if str(root.get('Status', '')).replace('minecraft:', '') in ('full', ''):
                    secs = {}
                    for s in root.get('sections', []):
                        bs = s.get('block_states') or {}
                        pal = [p.get('Name', '').replace('minecraft:', '') + ('[wl]' if (p.get('Properties') or {}).get('waterlogged') == 'true' else '')
                               for p in (bs.get('palette') or [])]
                        secs[s['Y']] = (pal, bs.get('data'))
            except Exception:
                secs = None
        self.chunks[k] = secs
        return secs

    def block(self, x, y, z):
        c = self._chunk(x >> 4, z >> 4)
        if c is None: return '?'
        s = c.get(y >> 4)
        if not s: return 'air'
        pal, data = s
        if not data: return pal[0] if pal else '?'
        bits = max(4, math.ceil(math.log2(len(pal)))); per = 64 // bits; mask = (1 << bits) - 1
        j = ((y & 15) << 8) | ((z & 15) << 4) | (x & 15)
        return pal[(data[j // per] >> ((j % per) * bits)) & mask]


# ---- the classes ---------------------------------------------------------------------------------------------------------------
# what the bots place (dirt turns grass in the light; the pathfinder's scaffold list, scaffold.mjs PATHFINDER_SCAFFOLD, less wood:
# a plank or a log in water is left alone -- the walkways this feeds ARE planks)
BOT_MAT = re.compile(r'^(dirt|coarse_dirt|rooted_dirt|grass_block|cobblestone|mossy_cobblestone|cobbled_deepslate|netherrack|stone|andesite|diorite|granite|deepslate|tuff|sandstone|red_sandstone|dripstone_block)$')
WATER = re.compile(r'^(water|bubble_column|kelp|kelp_plant|seagrass|tall_seagrass)$|\[wl\]$')
OPEN = re.compile(r'^(air|cave_air|short_grass|tall_grass|fern|large_fern|dead_bush|.*_flower|poppy|dandelion|.*_tulip|cornflower|azure_bluet|oxeye_daisy|allium|lily_of_the_valley|lily_pad|vine|snow|sugar_cane|.*_sapling|torch|wall_torch)$')
TREE = re.compile(r'_(leaves|log|wood)$')
N4 = ((1, 0), (-1, 0), (0, 1), (0, -1))


def surface(w, x, z, hi, lo=40):
    """A column's top: (y, name) of the first block from hi down that is not open air, a plant, a torch or a tree."""
    for y in range(hi, lo, -1):
        n = w.block(x, y, z)
        if n == '?': return None, '?'
        if OPEN.match(n) or TREE.search(n): continue
        return y, n
    return None, 'none'


def scan(live_path, gen_path, home, r, admin=frozenset()):
    L, G = World(live_path), World(gen_path)
    hx, hy, hz = home
    hi = hy + 24
    ctl = collections.Counter()
    cands, submerged = [], 0
    far_same = far_n = 0
    gwater, ltop = set(), {}
    for x in range(hx - r, hx + r + 1):
        for z in range(hz - r, hz + r + 1):
            d = max(abs(x - hx), abs(z - hz))
            gy, gn = surface(G, x, z, hi)
            if gn == '?': ctl['genesis_unread'] += 1; continue
            ly, ln = surface(L, x, z, hi)
            if ln == '?': ctl['live_unread'] += 1; continue
            ltop[(x, z)] = (ly, ln)
            ctl['cols'] += 1
            if d >= r - 8:
                far_n += 1; far_same += (gy == ly and gn == ln)
            if ln and BOT_MAT.match(ln): ctl['live_botmat_top'] += 1
            if gy is None or not WATER.search(gn): continue
            gwater.add((x, z))
            for y in range(gy - 3, gy):
                if BOT_MAT.match(L.block(x, y, z)) and WATER.search(G.block(x, y, z)): submerged += 1
            for y in range(gy, gy + 4):
                ln2, gn2 = L.block(x, y, z), G.block(x, y, z)
                if not BOT_MAT.match(ln2): continue
                if not (WATER.search(gn2) or OPEN.match(gn2)): continue
                # a natural change: lava near the cell at genesis (lava meeting water makes cobblestone and stone)
                if any(G.block(x + dx, y + dy, z + dz) == 'lava' for dx in (-2, -1, 0, 1, 2) for dz in (-2, -1, 0, 1, 2) for dy in (-2, -1, 0, 1)):
                    ctl['lava_guard'] += 1; continue
                if (x, y, z) in admin: ctl['admin_listed'] += 1; continue
                cands.append({'at': [x, y, z], 'name': ln2, 'genesis': gn2, 'wy': gy})
    # STANDING IN WATER (not land the bots made of a lake: a filled bay is ground now, and its grass is a meadow): a column whose
    # surface cell (at the genesis water level wy) is a candidate with live WATER on at least two of its four sides at wy; then a
    # candidate column with one water side beside a standing one (a line's shore end), twice. The other candidates are counted.
    surf = {(c['at'][0], c['at'][2]): c for c in cands if c['at'][1] == c['wy']}
    wet = {k: sum(1 for dx, dz in N4 if WATER.search(L.block(k[0] + dx, c['wy'], k[1] + dz))) for k, c in surf.items()}
    stand = {k for k, n in wet.items() if n >= 2}
    for _ in range(2):
        stand |= {k for k, n in wet.items() if n >= 1 and k not in stand and any((k[0] + dx, k[1] + dz) in stand for dx, dz in N4)}
    ctl['filled_land'] = sum(1 for c in cands if (c['at'][0], c['at'][2]) not in stand)
    cands = [c for c in cands if (c['at'][0], c['at'][2]) in stand]
    # the woodworks heuristic over the same columns (a bot material top, water on two opposite sides): how many genesis calls natural
    cand_cols = {(c['at'][0], c['at'][2]) for c in cands}
    heur = nat = 0
    for (x, z), (ly, ln) in ltop.items():
        if ly is None or not BOT_MAT.match(ln): continue
        w = lambda k: k in ltop and WATER.search(ltop[k][1] or '')
        if not ((w((x + 1, z)) and w((x - 1, z))) or (w((x, z + 1)) and w((x, z - 1)))): continue
        heur += 1
        if (x, z) not in cand_cols: nat += 1
    return {'home': home, 'r': r, 'at': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
            'controls': {**ctl, 'genesis_water_cols': len(gwater), 'far_ring_cols': far_n, 'far_ring_same': far_same,
                         'far_ring_agree': round(far_same / far_n, 4) if far_n else None, 'submerged_bot_blocks': submerged,
                         'heuristic': heur, 'heuristic_natural': nat, 'candidates': len(cands)},
            'cells': cands}


# ---- finish: records, place rows, traffic, lines --------------------------------------------------------------------------------
def latest_records(pooldir):
    """Every cell any project's newest record generation names (never listed: a wall or a path over water is a build)."""
    best = {}
    for f in glob.glob(f'{pooldir}/project-*.g*.json'):
        m = re.search(r'project-([-\d_]+)\.(\w+)\.g(\d+)\.json$', f)
        if not m: continue
        k = (m.group(1), m.group(2))
        if k not in best or int(m.group(3)) > best[k][0]: best[k] = (int(m.group(3)), f)
    cells = set()
    for _, f in best.values():
        try: d = json.load(open(f))
        except Exception: continue
        rec = d.get('record', d) if isinstance(d, dict) else {}
        for c in (rec.get('cells') or []):
            a = c.get('at') if isinstance(c, dict) else None
            if isinstance(a, list) and len(a) == 3: cells.add(tuple(a))
    return cells, len(best)


def open_log(p):
    return gzip.open(p, 'rt', errors='replace') if p.endswith('.gz') else open(p, 'r', errors='replace')


def logs_read(pattern, cells, days):
    """-> (placed rows by cell, traffic episodes by cell, totals). A FULL WALK of every file the pattern names (rotated included)."""
    since = time.time() - days * 86400
    keys = {(c[0], c[2]): c[1] for c in cells}
    placed, epis = collections.defaultdict(list), collections.defaultdict(set)
    tot = collections.Counter()
    for f in sorted(glob.glob(pattern)):
        # a rotated file last written before the window holds no row of it (the place rows began 11-08, inside every window)
        if os.path.getmtime(f) < since: tot['files_before_window'] += 1; continue
        tot['files'] += 1
        try:
            with open_log(f) as fh:
                for line in fh:
                    tot['lines'] += 1
                    if '"pos"' not in line or '"skill"' not in line: continue
                    try: r = json.loads(line)
                    except Exception: tot['bad'] += 1; continue
                    ts = r.get('@timestamp') or ''
                    try: t = time.mktime(time.strptime(ts[:19], '%Y-%m-%dT%H:%M:%S')) - time.timezone
                    except Exception: continue
                    sk = r.get('skill') or {}
                    if sk.get('name') == '_place_town':
                        a = sk.get('args') or {}
                        tot['place_rows'] += 1
                        if a.get('outcome') == 'placed' and keys.get((a.get('x'), a.get('z'))) == a.get('y'):
                            placed[(a['x'], a['y'], a['z'])].append(a.get('reason'))
                    if t < since: continue
                    p = (r.get('bot') or {}).get('pos')
                    if not p: continue
                    tot['pos_rows'] += 1
                    fx, fy, fz = math.floor(p['x']), math.floor(p['y'] + 1e-6), math.floor(p['z'])
                    if keys.get((fx, fz)) == fy - 1:
                        epis[(fx, fy - 1, fz)].add(((r.get('bot') or {}).get('name'), int(t // 600)))
                        tot['pos_on_cells'] += 1
        except OSError:
            tot['unreadable'] += 1
    return placed, epis, tot


def lines_of(cells):
    """4-connected groups of cells (|dy| <= 1 between neighbours) -> [[cell, ...], ...], biggest first. One cell a column: the
    highest (a pillar's lower blocks come out with it, top first, in the bot's cut order)."""
    by = {}
    for c in cells:
        k = (c['at'][0], c['at'][2])
        by.setdefault(k, []).append(c)
    top = {k: max(v, key=lambda c: c['at'][1]) for k, v in by.items()}
    seen, out = set(), []
    for k in sorted(top):
        if k in seen: continue
        q, comp = [k], []
        seen.add(k)
        while q:
            c = q.pop(); comp.append(c)
            for dx, dz in N4:
                n = (c[0] + dx, c[1] + dz)
                if n in top and n not in seen and abs(top[n]['at'][1] - top[c]['at'][1]) <= 1: seen.add(n); q.append(n)
        out.append(sorted((cc for kk in comp for cc in by[kk]), key=lambda c: (c['at'][0], c['at'][2], -c['at'][1])))
    return sorted(out, key=lambda l: -len(l))


WALK_EPISODES = 6     # a line bots stood on in at least this many (bot, 10-min) episodes over the window keeps a walkway ...
WALK_DAYS = 2         # ... on at least this many distinct days, and it is at least WALK_MIN cells long
WALK_MIN = 3


def finish(sc, pool, pooldir, logs, days):
    rec, nrec = latest_records(pooldir) if pooldir else (set(), 0)
    cells = [c for c in sc['cells'] if tuple(c['at']) not in rec]
    guarded = len(sc['cells']) - len(cells)
    placed, epis, tot = logs_read(logs, [c['at'] for c in cells], days) if logs else ({}, {}, collections.Counter())
    lines = []
    for i, comp in enumerate(lines_of(cells)):
        ep = set()
        for c in comp: ep |= epis.get(tuple(c['at']), set())
        dayset = {e[1] // 144 for e in ep}
        cols = {(c['at'][0], c['at'][2]) for c in comp}
        walk = len(ep) >= WALK_EPISODES and len(dayset) >= WALK_DAYS and len(cols) >= WALK_MIN
        lines.append({'id': f'L{i:03d}', 'walk': walk, 'episodes': len(ep), 'days': len(dayset),
                      'cells': [[*c['at'], c['name']] + ([1] if placed.get(tuple(c['at'])) else []) for c in comp]})
    return {'v': 1, 'pool': pool, 'home': sc['home'], 'r': sc['r'], 'generated': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
            'scanned': sc['at'], 'proof': 'genesis: Paper 1.21.8 build 60 (8de7c52c) from the world seed generates water or open air in the cell',
            'controls': {**sc['controls'], 'records': nrec, 'record_guarded': guarded, 'listed': len(cells), 'lines': len(lines),
                         'walk_lines': sum(1 for l in lines if l['walk']), 'walk_cells': sum(len(l['cells']) for l in lines if l['walk']),
                         'row_confirmed': sum(1 for c in cells if placed.get(tuple(c['at']))), 'logs': dict(tot), 'days': days,
                         'walk_rule': f'episodes>={WALK_EPISODES} (bot,10-min) on >={WALK_DAYS} days, >={WALK_MIN} columns'},
            'lines': lines}


def main():
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest='cmd', required=True)
    a = sp.add_parser('scan'); a.add_argument('--live', required=True); a.add_argument('--genesis', required=True)
    a.add_argument('--home', required=True); a.add_argument('--r', type=int, default=104); a.add_argument('--admin', default=None)
    b = sp.add_parser('finish'); b.add_argument('--scan', required=True); b.add_argument('--pool', required=True)
    b.add_argument('--pooldir', default=None); b.add_argument('--logs', default=None); b.add_argument('--days', type=int, default=7)
    o = ap.parse_args()
    if o.cmd == 'scan':
        admin = set()
        if o.admin and os.path.exists(o.admin):
            try:
                d = json.load(open(o.admin))
                for c in (d.get('cells') or d.get('placed') or []):
                    a2 = c.get('at') if isinstance(c, dict) else c
                    if isinstance(a2, list) and len(a2) == 3: admin.add(tuple(a2))
            except Exception:
                pass
        json.dump(scan(o.live, o.genesis, [int(v) for v in o.home.split(',')], o.r, frozenset(admin)), sys.stdout)
    else:
        json.dump(finish(json.load(open(o.scan)), o.pool, o.pooldir, o.logs, o.days), sys.stdout, separators=(',', ':'))


if __name__ == '__main__':
    main()
